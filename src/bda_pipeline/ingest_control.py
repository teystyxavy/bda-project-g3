def get_json(s3, key, bucket=BUCKET):
    """Read a small JSON control document from S3.

    Args:
        s3: boto3 S3 client.
        key: Object key.
        bucket: Bucket name (default: the data bucket; the dashboard bucket is
            used for ``dashboard/current.json``).

    Returns:
        ``(data, etag)``, or ``(None, None)`` if the object does not exist.
        The ETag is used for optimistic locking (``IfMatch``) on later writes.

    Raises:
        ValueError: if the document is larger than 1,000,000 bytes (control
        documents are tiny; anything bigger is unexpected).
    """
    # Prefix-scoped ListBucket permits reliable absence checks without broad listing.
    # (Without ListBucket, S3 reports a missing key as AccessDenied, not NoSuchKey.)
    listing = s3.list_objects_v2(Bucket=bucket, Prefix=key, MaxKeys=1)
    if not any(item['Key'] == key for item in listing.get('Contents', [])): return None, None
    try:
        item = s3.get_object(Bucket=bucket, Key=key)
    except s3.exceptions.NoSuchKey:
        # Deleted between the listing and the read.
        return None, None
    with item['Body'] as stream:
        data = stream.read(1_000_001)
    if len(data) > 1_000_000: raise ValueError('Control document too large')
    return json.loads(data), item['ETag']


def put_json(s3, key, data, **kwargs):
    """Write a JSON document to the data bucket (canonical bytes, SSE-S3 encrypted).

    Args:
        s3: boto3 S3 client.
        key: Object key.
        data: JSON-serialisable value.
        **kwargs: Extra ``put_object`` options, e.g. ``IfNoneMatch='*'`` for
            create-only writes.

    Returns:
        The ``put_object`` response.
    """
    return s3.put_object(Bucket=BUCKET, Key=key, Body=canonical(data),
                          ContentType='application/json', ServerSideEncryption='AES256', **kwargs)


def assert_marker(s3, prefix):
    """Require the Spark ``_SUCCESS`` marker for a Glue stage output.

    Spark writes an empty ``_SUCCESS`` file only after all output files are
    committed, so this proves the Glue job finished writing. The marker must
    be empty (0 bytes) and SSE-S3 encrypted, as the real Glue job writes it.

    Args:
        s3: boto3 S3 client.
        prefix: Stage prefix, e.g. ``pipeline/runs/<run>/curated``.

    Raises:
        ValueError: if the marker is not the expected empty encrypted file
        (a missing marker raises a botocore ``ClientError``).
    """
    marker = s3.head_object(Bucket=BUCKET, Key=prefix + '/_SUCCESS')
    if marker['ContentLength'] != 0 or marker.get('ServerSideEncryption') != 'AES256':
        raise ValueError('Require the encrypted real success marker')


def owned_lock(s3, run_id):
    """Confirm that ``run_id`` currently owns the pipeline lock.

    Returns:
        ``(lock_document, etag)``.

    Raises:
        ValueError: if there is no lock or another run owns it.
    """
    lock, etag = get_json(s3, 'pipeline/lock.json')
    if not lock or lock['run_id'] != run_id: raise ValueError('Run does not own the pipeline lock')
    return lock, etag


def release_lock(s3, run_id):
    """Delete the pipeline lock, but only if ``run_id`` still owns it.

    ``IfMatch=etag`` makes S3 refuse the delete if the lock object changed
    after it was read, so a run can never delete another run's lock.
    """
    _, etag = owned_lock(s3, run_id)
    s3.delete_object(Bucket=BUCKET, Key='pipeline/lock.json', IfMatch=etag)


GLUE_STAGES = [('curated', 'curate', '--output'), ('scored', 'score', '--OUTPUT'),
               ('baseline', 'baseline', '--OUTPUT'), ('export', 'export', '--OUTPUT'),
               ('network', 'network', '--OUTPUT')]
# Stages whose verified Glue output can be reused by an identical later run
# (baseline/export always re-verify from scratch, so they are not here). The
# workflow has a ReuseNetwork Choice state (like ReuseCurated/ReuseScores) that
# skips the Network Glue job on a cache hit, exactly like curate/score.
CACHED_STAGES = ['curated', 'scored', 'network']
# List prices used for the per-run cost estimate (ap-southeast-1). Glue 5.0
# bills per second with a one-minute minimum; a G.1X worker is 1 DPU and a
# G.2X worker 2 DPU. SageMaker training is the only job not run in Glue.
GLUE_USD_PER_DPU_HOUR = 0.44
GLUE_DPU_PER_WORKER = {'G.1X': 1, 'G.2X': 2, 'G.4X': 4, 'G.8X': 8}
SAGEMAKER_USD_PER_HOUR = {'ml.m5.2xlarge': 0.576, 'ml.m5.4xlarge': 1.152}


def stage_run_id(event):
    """Read the Glue task result without a fragile ASL field dereference.

    The start API calls this JobRunId; optimized .sync returns the completed
    JobRun object with Id. Missing IDs fail through the normal caught path.
    """
    result = event.get('job_result', {})
    run_id = event.get('job_run_id') or result.get('JobRunId') or result.get('JobRunID') or result.get('Id')
    if not isinstance(run_id, str) or not run_id:
        raise ValueError('Missing Glue job run ID')
    return run_id


def assert_glue_stage(glue, s3, run_id, stage, job_run_id, config):
    """Require the exact successful Glue run and its final encrypted commit marker."""
    job = glue.get_job_run(JobName=f'is459-g3-ingest-{stage}', RunId=job_run_id)['JobRun']
    args = job.get('Arguments', {})
    if (job.get('JobRunState') != 'SUCCEEDED' or args.get('--RUN_ID') != run_id
            or args.get('--STAGE') != stage or args.get('--DEPLOYMENT_SHA256') != sha(config)
            or args.get('--OUTPUT') != f"s3://{BUCKET}/{paths(run_id)[stage]}/"):
        raise ValueError('Unverified Glue stage identity or completion')
    assert_marker(s3, paths(run_id)[stage])


def owned_glue_runs(clients, run_id):
    """Find exact output-owned workers across all four Glue stages."""
    p = paths(run_id)
    for stage, suffix, argument in GLUE_STAGES:
        name = 'is459-g3-ingest-' + suffix
        for page in clients['glue'].get_paginator('get_job_runs').paginate(JobName=name):
            for job in page['JobRuns']:
                if job.get('Arguments', {}).get(argument) == f's3://{BUCKET}/{p[stage]}/':
                    yield name, job


def owned_training_jobs(clients, run_id):
    name = f'is459-g3-train-{run_id}'
    for page in clients['sagemaker'].get_paginator('list_training_jobs').paginate(NameContains=name):
        for job in page['TrainingJobSummaries']:
            if job['TrainingJobName'] == name:
                yield job


def no_active_workers(clients, run_id):
    """Never unlock while this run's Glue workers or training job are active."""
    for _, job in owned_glue_runs(clients, run_id):
        if job['JobRunState'] in ['STARTING', 'RUNNING', 'STOPPING', 'WAITING']:
            raise ValueError('A Glue worker is still active; preserve the lock')
    for job in owned_training_jobs(clients, run_id):
        if job['TrainingJobStatus'] in ['InProgress', 'Stopping']:
            raise ValueError('A SageMaker worker is still active; preserve the lock')


def stop_owned_workers(clients, run_id):
    """Stop only this run's four Glue stages and optional SageMaker training."""
    stopped = []
    for name, job in owned_glue_runs(clients, run_id):
        if job['JobRunState'] in ['STARTING', 'RUNNING', 'WAITING']:
            response = clients['glue'].batch_stop_job_run(JobName=name, JobRunIds=[job['Id']])
            if response.get('Errors'):
                raise ValueError('Glue cancellation was rejected; retain lock')
            stopped.append(job['Id'])
    sm = clients['sagemaker']
    for job in owned_training_jobs(clients, run_id):
        if job['TrainingJobStatus'] == 'InProgress':
            name = job['TrainingJobName']
            try:
                sm.stop_training_job(TrainingJobName=name)
            except sm.exceptions.ValidationException:
                if sm.describe_training_job(TrainingJobName=name)['TrainingJobStatus'] == 'InProgress':
                    raise
            stopped.append(name)
    return stopped


def compute_usage(clients, run_id, manifest, get_json, s3):
    """Measured runtime and estimated cost of every paid job in one run.

    Called at publish, when every job has finished. Every stage (``curate``,
    ``score``, ``baseline``, ``export``, ``network``) runs in Glue, found the
    same way as in ``owned_glue_runs`` (by its output argument); a stage
    served from the stage cache has no Glue run and is recorded as reused at
    USD 0. The only non-Glue job is optional SageMaker training, found by its
    deterministic name.

    Args:
        clients: Dict of boto3 clients (``glue``, ``sagemaker``).
        run_id: Run ID.
        manifest: The run's validated manifest (``train`` decides whether a
            training job is expected).
        get_json: ``(s3, key) -> (dict | None, etag)`` reader.
        s3: boto3 S3 client (to read ``evidence/stage-cache.json``).

    Returns:
        ``{'status': 'measured', 'glue': [...], 'sagemaker': [...], 'estimated_usd': total,
        'estimated_usd_is_upper_bound': bool}``. Dollar figures are list-price
        estimates, not an invoice; storage, requests, logs and orchestration
        are excluded. Each Glue entry's ``cost_basis`` says how it was
        computed: ``glue_reported_dpu_seconds`` (what Glue billed),
        ``workers_x_time`` (fixed workers) or ``max_workers_upper_bound`` (an
        auto-scaled run without reported DPU-seconds, so the maximum workers
        were assumed and the figure overstates the cost).
    """
    p = paths(run_id)
    cached, _ = get_json(s3, p['evidence'] + '/stage-cache.json')
    glue_jobs, total, upper_bound = [], 0.0, False
    for stage, job, argument in GLUE_STAGES:
        if (cached or {}).get(stage, {}).get('hit'):
            glue_jobs.append({'stage': stage, 'reused': True, 'estimated_usd': 0.0})
            continue
        runs = [run for page in clients['glue'].get_paginator('get_job_runs').paginate(JobName='is459-g3-ingest-' + job)
                for run in page['JobRuns'] if run.get('Arguments', {}).get(argument) == f's3://{BUCKET}/{p[stage]}/']
        for run in runs:
            seconds = run.get('ExecutionTime', 0)
            dpu = run.get('NumberOfWorkers', 0) * GLUE_DPU_PER_WORKER.get(run.get('WorkerType'), 0)
            # Glue reports DPUSeconds only for auto-scaling/Flex runs; otherwise workers x time.
            # For an auto-scaled run, NumberOfWorkers is the maximum, so the
            # fallback is an upper bound and is labelled as one.
            auto_scaled = run.get('Arguments', {}).get('--enable-auto-scaling') == 'true'
            if run.get('DPUSeconds'):
                dpu_seconds, basis = run['DPUSeconds'], 'glue_reported_dpu_seconds'
            else:
                dpu_seconds = dpu * max(seconds, 60)
                basis = 'max_workers_upper_bound' if auto_scaled else 'workers_x_time'
            usd = round(dpu_seconds / 3600 * GLUE_USD_PER_DPU_HOUR, 4)
            total += usd
            upper_bound = upper_bound or basis == 'max_workers_upper_bound'
            glue_jobs.append({'stage': stage, 'reused': False, 'state': run['JobRunState'], 'seconds': seconds,
                              'worker_type': run.get('WorkerType'), 'workers': run.get('NumberOfWorkers'),
                              'auto_scaled': auto_scaled, 'cost_basis': basis,
                              'dpu_hours': round(dpu_seconds / 3600, 4), 'estimated_usd': usd})
    sagemaker_jobs = []
    if manifest['train']:
        name = 'is459-g3-train-' + run_id
        job = clients['sagemaker'].describe_training_job(TrainingJobName=name)
        instance, count = job['ResourceConfig']['InstanceType'], job['ResourceConfig']['InstanceCount']
        seconds = job.get('BillableTimeInSeconds') or job.get('TrainingTimeInSeconds', 0)
        rate = SAGEMAKER_USD_PER_HOUR.get(instance)
        usd = round(seconds / 3600 * count * rate, 4) if rate is not None else None
        total += usd or 0.0
        sagemaker_jobs.append({'stage': 'train', 'instance_type': instance, 'instances': count,
                               'seconds': round(seconds, 1), 'estimated_usd': usd})
    return {'status': 'measured', 'glue': glue_jobs, 'sagemaker': sagemaker_jobs, 'estimated_usd': round(total, 4),
            'estimated_usd_is_upper_bound': upper_bound,
            'rates': {'glue_usd_per_dpu_hour': GLUE_USD_PER_DPU_HOUR, 'sagemaker_usd_per_hour': SAGEMAKER_USD_PER_HOUR},
            'scope': 'List-price estimate of Glue and SageMaker compute only; not an invoice.'}


def handle(event, config, clients):
    """Dispatch one control-plane operation (see the module docstring for the flow).

    Every operation re-reads and re-validates the run manifest (except
    ``recover``/``failed``), so nothing in the Step Functions state can steer
    the pipeline to a different input or deployment.

    Args:
        event: ``{'op': ..., 'run_id': ..., ...}`` from Step Functions or the
            CLI, or a raw EventBridge "Execution Status Change" event.
        config: Deployed pipeline configuration (from the ``PIPELINE_CONFIG``
            environment variable): image URI, role ARNs, model prefix and
            manifest hash, CloudFront distribution ID, dashboard URL, stage
            versions.
        clients: Dict of boto3 clients (s3, glue, sagemaker,
            stepfunctions, cloudfront).

    Returns:
        Operation-specific dict that Step Functions stores in its state (e.g.
        Glue arguments, a SageMaker job request, or the publish result).

    Raises:
        ValueError: on any failed check. Step Functions then catches the error
        and goes to ``RecordFailure``.
    """
    s3, glue, sm = [clients[name] for name in ['s3', 'glue', 'sagemaker']]
    # ---- EventBridge terminal-execution event -> translate into op='failed' ----
    if event.get('source') == 'aws.states':
        detail = event['detail']
        prefix = f'arn:aws:states:{REGION}:{ACCOUNT}:execution:is459-g3-ingest:'
        if not detail.get('executionArn', '').startswith(prefix) or detail.get('status') not in ['FAILED', 'ABORTED', 'TIMED_OUT']:
            raise ValueError('Unexpected cancellation event')
        # The execution name *is* the run ID, so it is the suffix of the ARN.
        event = {'op': 'failed', 'run_id': detail['executionArn'][len(prefix):],
                 'failure': {'Error': detail['status'], 'Cause': 'Terminal execution event'}}
    run_id = valid_run(event['run_id'])
    p = paths(run_id)
    op = event['op']
    # ---- recover: manual unlock after a failed run (ingest.py unlock) ----
    if op == 'recover':
        arn = f'arn:aws:states:{REGION}:{ACCOUNT}:execution:is459-g3-ingest:{run_id}'
        state = clients['stepfunctions'].describe_execution(executionArn=arn)['status']
        # Never unlock a run that is still RUNNING or that SUCCEEDED.
        if state not in ['FAILED', 'ABORTED', 'TIMED_OUT']:
            raise ValueError('Only a terminal unsuccessful execution can be recovered')
        owned_lock(s3, run_id)
        no_active_workers(clients, run_id)
        release_lock(s3, run_id)
        return {'status': 'lock-released', 'run_id': run_id, 'outputs_preserved': True}
    # ---- failed: record evidence and stop this run's workers ----
    # May be called twice (RecordFailure state and EventBridge), so it is idempotent:
    # only the first failure.json is kept.
    if op == 'failed':
        failure, _ = get_json(s3, f"{p['evidence']}/failure.json")
        if failure is None:
            put_json(s3, f"{p['evidence']}/failure.json", {'run_id': run_id, 'failure': event.get('failure')})
        lock, _ = get_json(s3, 'pipeline/lock.json')
        if lock and lock.get('run_id') == run_id:
            stopped = stop_owned_workers(clients, run_id)
            put_json(s3, f"{p['evidence']}/cancellation.json", {'run_id': run_id, 'stop_requested': stopped, 'lock_preserved': True})
        return {'status': 'failed-output-preserved', 'run_id': run_id}
    # ---- processing_failed: SageMaker job failed or exceeded 300 polls ----
    # Raising here sends the workflow into RecordFailure.
    if op == 'training_failed':
        raise ValueError('Training failed, stopped or exceeded the bounded completion deadline')
    # All remaining ops work on a validated manifest that matches this
    # deployment and the frozen model.
    manifest, _ = get_json(s3, f"{p['raw']}/manifest.json")
    validate_manifest(manifest, sha(config))
    if manifest['run_id'] != run_id or manifest['model_manifest_sha256'] != config['model_manifest_sha256']:
        raise ValueError('Manifest/run/model mismatch')
    # ---- begin: first state of the workflow ----
    if op == 'begin':
        lock, _ = get_json(s3, 'pipeline/lock.json')
        # Create-only write: if two runs race, only one succeeds.
        if lock is None:
            put_json(s3, 'pipeline/lock.json', {'run_id': run_id}, IfNoneMatch='*')
        else: owned_lock(s3, run_id)
        # Uploaded raw files must match the manifest's sizes and the sha256
        # stored in object metadata at upload time.
        for name, info in manifest['files'].items():
            item = s3.head_object(Bucket=BUCKET, Key=f"{p['raw']}/{name}")
            if item['ContentLength'] != info['bytes'] or item.get('Metadata', {}).get('sha256') != info['sha256']:
                raise ValueError('Uploaded raw input contract mismatch')
        # Never overwrite an existing run's outputs.
        for prefix in [p['curated'], p['scored'], p['baseline'], p['export'], p['network']]:
            if s3.list_objects_v2(Bucket=BUCKET, Prefix=prefix + '/', MaxKeys=1).get('KeyCount', 0):
                raise ValueError('Output already exists; preserve it and use a new run')
        # Try to reuse verified Glue outputs from an identical earlier run.
        cached = {stage: reuse(s3, stage, manifest, config, get_json) for stage in CACHED_STAGES}
        put_json(s3, p['evidence'] + '/stage-cache.json', cached)
        # Stored as $.work in the state machine; drives the cache Choice states
        # and the Glue job arguments.
        profile = run_profile(manifest['rows'])
        return {'train': manifest['train'], 'rows': manifest['rows'],
            'glue_workers': profile['glue_workers'],
            'glue_timeout': profile['glue_timeout'],
            'curated_cache_hit': cached['curated']['hit'], 'scored_cache_hit': cached['scored']['hit'],
            'network_cache_hit': cached['network']['hit'],
            'curate_arguments': {'--transactions': f"s3://{BUCKET}/{p['raw']}/transactions.csv",
                '--accounts': f"s3://{BUCKET}/{p['raw']}/accounts.csv", '--fx': f"s3://{BUCKET}/{p['raw']}/fx.csv",
                '--output': f"s3://{BUCKET}/{p['curated']}/", '--expected_rows': str(manifest['rows']),
                '--behaviour': 'true', '--subset': manifest['subset'],
                '--start_date': manifest['start_date'], '--end_date': manifest['end_date'],
                '--shuffle_partitions': str(profile['shuffle_partitions']), '--TempDir': f's3://{BUCKET}/tmp/ingest/{run_id}/curate/'},
            'score_arguments': {'--INPUT': f"s3://{BUCKET}/{p['curated']}/",
                '--OUTPUT': f"s3://{BUCKET}/{p['scored']}/", '--EXPECTED_ROWS': str(manifest['rows']),
                '--TempDir': f's3://{BUCKET}/tmp/ingest/{run_id}/score/'},
            'network_arguments': {'--INPUT': f"s3://{BUCKET}/{p['curated']}/",
                '--OUTPUT': f"s3://{BUCKET}/{p['network']}/", '--EXPECTED_ROWS': str(manifest['rows']),
                '--SHUFFLE_PARTITIONS': str(profile['shuffle_partitions']),
                '--enable-auto-scaling': 'true',
                '--TempDir': f's3://{BUCKET}/tmp/ingest/{run_id}/network/'}}
    # ---- publish (early path): already published -> make the call idempotent ----
    # If a previous Publish attempt finished but its response was lost (e.g. a
    # Lambda retry), just register caches, release the lock and return the result.
    if op == 'publish':
        completed, _ = get_json(s3, f"{p['evidence']}/result.json")
        if completed and completed.get('status') == 'published':
            for stage in CACHED_STAGES:
                register(s3, stage, manifest, config, get_json, put_json)
            lock, _ = get_json(s3, 'pipeline/lock.json')
            if lock and lock.get('run_id') == run_id: release_lock(s3, run_id)
            return completed
    # Every op below requires that this run holds the lock.
    owned_lock(s3, run_id)
    # ---- curated: Glue curate finished -> register Athena table, start baseline ----
    if op == 'curated':
        assert_marker(s3, p['curated'])
        table = 'run_' + run_id.replace('-', '_')
        location = f"s3://{BUCKET}/{p['curated']}/"
        # External Parquet table with *partition projection*: Athena computes
        # the txn_date=YYYY-MM-DD partition folders from the date range instead
        # of needing a Glue crawler or MSCK REPAIR to discover them. Lets an
        # analyst query this run's curated data ad hoc; the pipeline itself
        # no longer reads through this table (network analysis runs in Glue).
        # Only a representative subset of columns is declared.
        definition = {'Name': table, 'TableType': 'EXTERNAL_TABLE',
            'Parameters': {'classification': 'parquet', 'projection.enabled': 'true',
                'projection.txn_date.type': 'date', 'projection.txn_date.range': f"{manifest['start_date']},{manifest['end_date']}",
                'projection.txn_date.format': 'yyyy-MM-dd', 'projection.txn_date.interval': '1',
                'projection.txn_date.interval.unit': 'DAYS', 'storage.location.template': location + 'txn_date=${txn_date}/'},
            'PartitionKeys': [{'Name': 'txn_date', 'Type': 'string'}],
            'StorageDescriptor': {'Location': location,
                'Columns': [{'Name': name, 'Type': kind} for name, kind in [
                    ('from_bank', 'string'), ('to_bank', 'string'), ('payment_currency', 'string'),
                    ('receiving_currency', 'string'), ('amount_usd', 'double')]],
                'InputFormat': 'org.apache.hadoop.hive.ql.io.parquet.MapredParquetInputFormat',
                'OutputFormat': 'org.apache.hadoop.hive.ql.io.parquet.MapredParquetOutputFormat',
                'SerdeInfo': {'SerializationLibrary': 'org.apache.hadoop.hive.ql.io.parquet.serde.ParquetHiveSerDe'}}}
        try:
            glue.create_table(DatabaseName=DATABASE, TableInput=definition)
        except glue.exceptions.AlreadyExistsException:
            # Tolerate a retry, but only if the table points at this run's data.
            existing = glue.get_table(DatabaseName=DATABASE, Name=table)['Table']
            if existing['StorageDescriptor']['Location'] != location:
                raise ValueError('Existing run table has a different source')
        # Becomes $.baseline_request; Step Functions passes it to Glue StartJobRun.
        return stage_request(run_id, 'baseline', config, subset=manifest['subset'], rows=manifest['rows'])
    # ---- baseline: baseline job done -> optionally build a training job request ----
    if op == 'baseline':
        assert_glue_stage(glue, s3, run_id, 'baseline', stage_run_id(event), config)
        proof, _ = get_json(s3, f"{p['baseline']}/proof.json")
        if not proof or proof.get('status') != 'passed' or proof.get('rows') != manifest['rows']:
            raise ValueError('Baseline processing is not verified')
        name = 'is459-g3-train-' + run_id
        training = None
        if manifest['train']:
            # Copy the verified baseline files into a training-job-specific
            # prefix, matching the 'baseline' and 'manifest' input channels.
            for source, target in [('baseline/bq1_scored.parquet', 'baseline/bq1_scored.parquet'),
                                   ('manifest/dashboard.json', 'manifest/dashboard.json'), ('manifest/input.json', 'manifest/input.json')]:
                s3.copy_object(Bucket=BUCKET, Key=f'sagemaker/inputs/{name}/{target}',
                    CopySource={'Bucket': BUCKET, 'Key': f"{p['baseline']}/{source}"}, ServerSideEncryption='AES256')
            # SageMaker CreateTrainingJob request sized by the run's profile (see
            # ingest_contract.RUN_PROFILES): no internet (network isolation), no
            # Spot (so the job cannot be interrupted mid-run). The output is
            # only a *candidate*; export_stage verifies it and never promotes it.
            training = training_job_request(name, config['image_uri'], manifest['rows'])
        # None -> the workflow's TrainRequested Choice goes to ReuseFrozen.
        return {'training_request': training}
    # ---- export: all parallel branches done -> verify network output, build export job ----
    if op == 'export':
        assert_marker(s3, p['scored'])
        baseline, _ = get_json(s3, f"{p['baseline']}/proof.json")
        if not baseline or baseline.get('status') != 'passed' or baseline.get('rows') != manifest['rows']:
            raise ValueError('Export requires independent baseline verification')
        assert_marker(s3, p['network'])
        extra = {'network': p['network'] + '/'}
        if manifest['train']:
            trained = sm.describe_training_job(TrainingJobName='is459-g3-train-' + run_id)
            expected = f'sagemaker/outputs/is459-g3-train-{run_id}/output/model.tar.gz'
            if trained['TrainingJobStatus'] != 'Completed' or trained['ModelArtifacts']['S3ModelArtifacts'] != f's3://{BUCKET}/{expected}':
                raise ValueError('Unexpected candidate training output')
            extra['candidate'] = expected
        # Becomes $.export_request for the Export Glue job.
        return stage_request(run_id, 'export', config, extra, subset=manifest['subset'], rows=manifest['rows'])
    # ---- publish: verify the release, then make it live on the dashboard ----
    if op == 'publish':
        # A date-subset run's export stage skips building a release entirely (see
        # ingest_compute.export_stage) - the Export Glue job still exits 0, so the workflow
        # reaches Publish regardless. Mirror that skip here instead of failing on a release
        # that was never meant to exist.
        if manifest.get('export_dates'):
            return {'status': 'publish-skipped', 'run_id': run_id, 'reason': 'date-subset run has no public release'}
        assert_glue_stage(glue, s3, run_id, 'export', stage_run_id(event), config)
        release, _ = get_json(s3, f"{p['export']}/release/manifest.json")
        # The release must come from a completed export of *this* run, with
        # passed score/network (and, if requested, training) verification,
        # and contain exactly the four expected dashboard files.
        if (not release or release['pipeline_run_id'] != run_id
                or release['processing_sha256'] != manifest['processing_sha256']
                or any(release['verification'][kind]['status'] != 'passed' for kind in ['scores', 'network'])
                or len(release['files']) != len(ASSETS)
                or {item['file'] for item in release['files']} != set(ASSETS)
                or (manifest['train'] and release['verification'].get('training', {}).get('status') != 'passed')):
            raise ValueError('Unverified or incomplete release')
        # Load each file within the shared release budgets, check its
        # size and SHA-256 against the manifest, and scan for secrets or
        # private paths (SENSITIVE_TEXT) before anything becomes public.
        blobs = {}
        for item in release['files']:
            if not 0 < item['bytes'] <= ASSET_MAX_BYTES[item['file']]: raise ValueError('Oversized release file')
            response = s3.get_object(Bucket=BUCKET, Key=f"{p['export']}/release/site/{item['file']}")
            with response['Body'] as stream: data = stream.read(ASSET_MAX_BYTES[item['file']] + 1)
            if len(data) != item['bytes'] or hashlib.sha256(data).hexdigest() != item['sha256']:
                raise ValueError('Release file hash mismatch')
            if SENSITIVE_TEXT.search(data.decode('utf-8')): raise ValueError('Private content in release')
            blobs[item['file']] = data
        if sum(map(len, blobs.values())) > RELEASE_MAX_BYTES: raise ValueError('Release too large')
        snapshot = json.loads(blobs['dashboard.json'])
        # Recursive check for credential-like keys and row-level labels in the queue.
        _inspect(snapshot)
        if snapshot['pipeline']['run_id'] != run_id or snapshot.get('buildStatus') != 'complete':
            raise ValueError('Release snapshot provenance mismatch')
        # 1) Immutable, versioned copy of this release; safe to cache for a year.
        for name, data in blobs.items():
            s3.put_object(Bucket=SITE_BUCKET, Key=f'dashboard/releases/{run_id}/{name}', Body=data,
                ContentType=ASSETS[name], ServerSideEncryption='AES256', CacheControl='public,max-age=31536000,immutable')
        # 2) Top-level shell files (no-cache so browsers revalidate).
        # Compatible shell assets can load either the previous snapshot or the new pointer.
        for name in ['index.html', 'dashboard.js', 'dashboard.css']:
            s3.put_object(Bucket=SITE_BUCKET, Key=f'dashboard/{name}', Body=blobs[name],
                ContentType=ASSETS[name], ServerSideEncryption='AES256', CacheControl='no-cache')
        # 3) Switch the "current release" pointer. The conditional write
        # (IfMatch on the old ETag, or IfNoneMatch for the first release) means
        # a concurrent change to the pointer makes this write fail instead of
        # being silently overwritten. previous_run_id records the prior release.
        pointer, etag = get_json(s3, 'dashboard/current.json', SITE_BUCKET)
        new_pointer = {'schema_version': 1, 'run_id': run_id, 'snapshot': f'releases/{run_id}/dashboard.json',
                       'sha256': hashlib.sha256(blobs['dashboard.json']).hexdigest(), 'previous_run_id': pointer.get('run_id') if pointer else None}
        if not pointer or pointer['run_id'] != run_id:
            s3.put_object(Bucket=SITE_BUCKET, Key='dashboard/current.json', Body=canonical(new_pointer),
                ContentType='application/json', ServerSideEncryption='AES256', CacheControl='no-store,max-age=0',
                **({'IfMatch': etag} if etag else {'IfNoneMatch': '*'}))
        # 4) Ask CloudFront to drop its cached copies of the mutable paths.
        # CallerReference is per run, so a retried publish does not create a
        # second invalidation.
        clients['cloudfront'].create_invalidation(DistributionId=config['distribution_id'],
            InvalidationBatch={'Paths': {'Quantity': 4, 'Items': ['/', '/index.html', '/dashboard.js', '/current.json']},
                               'CallerReference': 'ingest-' + run_id})
        result = {'status': 'published', 'run_id': run_id, 'processing_sha256': manifest['processing_sha256'],
                  'dashboard_url': config['dashboard_url'], 'release_url': config['dashboard_url'] + f'releases/{run_id}/index.html',
                  'training_requested': manifest['train'], 'model_promoted': False}
        # Measured runtime/cost is informational only, so a measurement failure
        # (e.g. a Glue/SageMaker API hiccup) must never block a verified publish.
        try:
            result['usage'] = compute_usage(clients, run_id, manifest, get_json, s3)
        except Exception as error:
            result['usage'] = {'status': 'unavailable', 'error': str(error)}
        # 5) Record results: the result cache (keyed by processing identity, so
        # an identical future run can skip all work), this run's evidence,
        # stage-cache receipts, and finally release the lock.
        put_json(s3, f"pipeline/cache/{manifest['processing_sha256']}.json", result)
        put_json(s3, f"{p['evidence']}/result.json", result)
        for stage in CACHED_STAGES:
            register(s3, stage, manifest, config, get_json, put_json)
        release_lock(s3, run_id)
        return result
    raise ValueError('Unsupported operation')


def lambda_handler(event, context):
    """AWS Lambda entry point for ``is459-g3-ingest-control``.

    Loads the deployed pipeline configuration from the ``PIPELINE_CONFIG``
    environment variable (set by Terraform), creates boto3 clients with short
    timeouts and at most 2 attempts (Step Functions adds its own retries for
    Lambda service errors), and delegates to ``handle``.

    boto3 is imported inside the function so the rest of the module can be
    imported and unit-tested without AWS libraries.

    Args:
        event: Step Functions / EventBridge / CLI event.
        context: Lambda context (unused).

    Returns:
        Whatever ``handle`` returns.
    """
    import boto3
    from botocore.config import Config
    config = json.loads(os.environ['PIPELINE_CONFIG'])
    sdk = Config(retries={'mode': 'standard', 'total_max_attempts': 2},
                 connect_timeout=5, read_timeout=20, user_agent_appid='AWSSkill-SageMaker')
    session = boto3.Session(region_name=REGION)
    clients = {name: session.client(name, config=sdk) for name in
               ['s3', 'glue', 'sagemaker', 'stepfunctions', 'cloudfront']}
    return handle(event, config, clients)
