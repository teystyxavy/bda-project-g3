"""Small AWS control plane. No dataframe libraries; no paid-compute retry loop.

What this file is
-----------------
The code of the ``is459-g3-ingest-control`` Lambda (Python 3.12, 1024 MB,
120 s timeout, reserved concurrency 1; handler
``bda_pipeline.ingest_control.lambda_handler``; see
``infra/ingestion/main.tf``). It is the "brain" of the batch Step Functions
state machine ``is459-g3-ingest`` (generated by
``infra/ingestion/build-workflow.py``). Step Functions itself runs the
expensive work (Glue jobs, SageMaker jobs); between those steps it calls this
Lambda with ``{'op': <operation>, 'run_id': ...}`` to check what just
happened and to build the request for the next step.

Workflow and the ``op`` values handled by ``handle``::

    Begin  (op=begin)      take the run lock, check raw uploads, try stage cache,
                           return Glue arguments for curate/score/network
    Curate (Glue)          skipped on a curated cache hit
    PrepareBaseline (op=curated)   register Athena table, return baseline job request
    ScoreAndAnalyze (parallel):
        Baseline (Glue) -> PrepareBranches (op=baseline)
            -> optional Train (SageMaker Training)
        Score (Glue)                     skipped on a scored cache hit
        Network (Glue)                   mule-network detection; skipped on a network cache hit
    PrepareExport (op=export)      verify network output, return export job request
    Export (Glue)
    Publish (op=publish)           verify release, copy to dashboard bucket,
                                   update pointer, invalidate CloudFront, unlock
    RecordFailure (op=failed)      on any error: record evidence, stop workers

Two more entry points:

* ``op='recover'`` - invoked by ``scripts/ingestion/ingest.py unlock`` to
  release the lock after a failed run once all workers have stopped.
* An EventBridge rule (``is459-g3-ingest-terminal-cleanup``) sends
  "Step Functions Execution Status Change" events for FAILED / TIMED_OUT /
  ABORTED executions, so that workers are stopped even if the state machine
  itself was aborted (when ``RecordFailure`` never runs).

Concurrency control
-------------------
Only one run may be in progress at a time. ``pipeline/lock.json`` in the data
bucket holds the owning ``run_id``; it is created with a conditional write
(``IfNoneMatch='*'``) and deleted with ``IfMatch=<etag>``, so two runs can
never both believe they own it. After a failure the lock is deliberately
*kept* until someone confirms no paid worker is still running.

Why "no retry loop": Step Functions retries only Lambda service errors, never
paid Glue/SageMaker jobs; a failed run keeps its outputs as evidence and a new
run ID must be used.
"""
